#!/usr/bin/env node
/* Packs assets/models/*.glb into assets/models.js (base64) so the game works from file:// without fetch.
   Usage: node tools/pack-assets.js   (re-run whenever you add or change a .glb) */
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'assets', 'models');
const out = path.join(__dirname, '..', 'assets', 'models.js');
const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter(f => /\.glb$/i.test(f)) : [];
let js = '/* generated by tools/pack-assets.js – do not edit */\nwindow.MEO = window.MEO || {};\nMEO.ASSET_B64 = MEO.ASSET_B64 || {};\n';
files.forEach(f => { js += 'MEO.ASSET_B64[' + JSON.stringify(f.replace(/\.glb$/i, '')) + '] = "' + fs.readFileSync(path.join(dir, f)).toString('base64') + '";\n'; });
fs.writeFileSync(out, js);
console.log('packed ' + files.length + ' model(s): ' + files.map(f => f.replace(/\.glb$/i, '')).join(', '));
